create extension if not exists pgcrypto;

create table if not exists public.countries (
  iso_alpha2 text primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.clubs (
  club_id uuid primary key default gen_random_uuid(),
  club_name varchar(255) not null,
  description text null,
  location varchar(255) null,
  coordinator_id text null,
  created_at timestamptz null default now(),
  is_active boolean null default true,
  country text null
);

create table if not exists public.profiles (
  profile_id uuid primary key references auth.users(id) on delete cascade,
  legacy_registration_id uuid unique null references public.registrations(registration_id) on delete set null,
  username text unique,
  display_name text,
  country_code text null references public.countries(iso_alpha2),
  avatar_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.roles (
  role_id bigint generated by default as identity primary key,
  role_name text unique not null
);

insert into public.roles (role_name)
values
  ('super_admin'),
  ('country_admin'),
  ('club_coordinator'),
  ('user')
on conflict (role_name) do nothing;

create table if not exists public.user_role_assignments (
  assignment_id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(profile_id) on delete cascade,
  role_id bigint not null references public.roles(role_id) on delete cascade,
  country_code text null references public.countries(iso_alpha2),
  club_id uuid null references public.clubs(club_id) on delete cascade,
  assigned_by uuid null references public.profiles(profile_id) on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint user_role_assignments_club_country_check check (
    not (club_id is not null and country_code is not null)
  ),
  constraint unique_role_scope unique nulls not distinct (user_id, role_id, country_code, club_id)
);

create table if not exists public.admin_action_logs (
  log_id bigint generated by default as identity primary key,
  actor_user_id uuid null references public.profiles(profile_id) on delete set null,
  action_type text not null,
  target_user_id uuid null references public.profiles(profile_id) on delete set null,
  target_country_code text null references public.countries(iso_alpha2),
  target_club_id uuid null references public.clubs(club_id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_invites (
  invite_id uuid primary key default gen_random_uuid(),
  email text not null,
  role_id bigint not null references public.roles(role_id) on delete cascade,
  country_code text null references public.countries(iso_alpha2),
  club_id uuid null references public.clubs(club_id) on delete cascade,
  invited_by uuid null references public.profiles(profile_id) on delete set null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  expires_at timestamptz null,
  accepted_by uuid null references public.profiles(profile_id) on delete set null,
  constraint admin_invites_status_check check (status in ('pending', 'accepted', 'revoked', 'expired'))
);

create index if not exists idx_profiles_legacy_registration_id
