  on public.admin_action_logs (target_club_id)
  where target_club_id is not null;

create index if not exists idx_admin_invites_email
  on public.admin_invites (email);

create or replace function public.handle_new_auth_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (
    profile_id,
    username,
    display_name,
    avatar_url
  )
  values (
    new.id,
    lower(coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1), new.id::text)),
    coalesce(new.raw_user_meta_data ->> 'display_name', new.raw_user_meta_data ->> 'full_name'),
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (profile_id) do nothing;

  return new;
end;
$$;

create or replace function public.validate_role_scope(
  p_role_id bigint,
  p_country_code text,
  p_club_id uuid
)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_role_name text;
begin
  select role_name
  into v_role_name
  from public.roles
  where role_id = p_role_id;

  if v_role_name is null then
    return false;
  end if;

  if p_country_code is not null and p_club_id is not null then
    return false;
  end if;

  if v_role_name = 'country_admin' and p_country_code is null then
    return false;
  end if;

  if v_role_name = 'club_coordinator' and p_club_id is null and p_country_code is null then
    return false;
  end if;

  return true;
end;
$$;

create or replace function public.enforce_user_role_assignment_scope()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.validate_role_scope(new.role_id, new.country_code, new.club_id, null::uuid) then
    raise exception 'Invalid role scope for assignment';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_enforce_user_role_assignment_scope on public.user_role_assignments;
create trigger trg_enforce_user_role_assignment_scope
  before insert or update on public.user_role_assignments
  for each row execute function public.enforce_user_role_assignment_scope();

